type Messages = (typeof translations)["en"];

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  messages: Messages;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  children,
  initialLocale,
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  const [locale, setLocale] = useState<Locale>(initialLocale ?? "en");

  useEffect(() => {
    if (typeof window === "undefined") return;
    const { locale: pathLocale } = stripLocalePath(
      window.location?.pathname ?? "/"
    );
    const stored = localStorage.getItem("docuforge-locale");
    const queryLocale = new URLSearchParams(window.location.search).get("lang");

    let nextLocale: Locale | null = null;
    if (pathLocale) {
      nextLocale = pathLocale;
    } else if (queryLocale) {
      nextLocale = normalizeLocale(queryLocale);
    } else if (stored) {
      nextLocale = normalizeLocale(stored);
    } else if (!initialLocale && typeof navigator !== "undefined") {
      nextLocale = normalizeLocale(navigator.language);
    } else if (initialLocale) {
      nextLocale = initialLocale;
    }

    if (nextLocale && nextLocale !== locale) {
      setLocale(nextLocale);
    }
  }, [initialLocale]);

  useEffect(() => {
    if (typeof window === "undefined") return;
    localStorage.setItem("docuforge-locale", locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.cookie = `docuforge-locale=${locale}; path=/; max-age=31536000; samesite=lax`;
  }, [locale]);

  const messages = useMemo(() => translations[locale] ?? translations.en, [locale]);

  return (
    <I18nContext.Provider value={{ locale, setLocale, messages }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}

