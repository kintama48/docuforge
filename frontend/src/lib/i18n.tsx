type Messages = (typeof translations)[Locale];

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  messages: Messages;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function resolveInitialLocale(initialLocale?: Locale): Locale {
  // Keep client and server first paint aligned to avoid hydration mismatch.
  if (initialLocale) return initialLocale;
  if (typeof window === "undefined") return "en";

  const { locale: pathLocale, basePath } = stripLocalePath(
    window.location?.pathname ?? "/"
  );
  const stored = localStorage.getItem("docuforge-locale");
  const queryLocale = new URLSearchParams(window.location.search).get("lang");

  if (pathLocale) return pathLocale;
  if (queryLocale) return normalizeLocale(queryLocale);
  if (shouldUseClientLocalePreference(basePath) && stored) {
    return normalizeLocale(stored);
  }
  if (
    shouldUseClientLocalePreference(basePath) &&
    typeof navigator !== "undefined"
  ) {
    return normalizeLocale(navigator.language);
  }
  return "en";
}

export function I18nProvider({
  children,
  initialLocale,
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  const [locale, setLocale] = useState<Locale>(() => resolveInitialLocale(initialLocale));

  useEffect(() => {
    if (typeof window === "undefined") return;

    const { locale: pathLocale, basePath } = stripLocalePath(
      window.location?.pathname ?? "/"
    );
    const queryLocale = new URLSearchParams(window.location.search).get("lang");
    const stored = localStorage.getItem("docuforge-locale");

    const detected = pathLocale
      ?? (queryLocale ? normalizeLocale(queryLocale) : null)
      ?? (
        shouldUseClientLocalePreference(basePath) && stored
          ? normalizeLocale(stored)
          : null
      );

    if (detected && detected !== locale) {
      const timer = window.setTimeout(() => {
        setLocale(detected);
      }, 0);
      return () => window.clearTimeout(timer);
    }
  }, [locale]);

  useEffect(() => {
    if (typeof window === "undefined") return;
    localStorage.setItem("docuforge-locale", locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.cookie = `docuforge-locale=${locale}; path=/; max-age=31536000; samesite=lax`;
  }, [locale]);

  const messages = useMemo(() => translations[locale] ?? translations.en, [locale]);

  return (
    <I18nContext.Provider value={{ locale, setLocale, messages }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}

