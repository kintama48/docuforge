      "experience": [
        {
          "title": "Senior Software Engineer",
          "company": "Tech Corp",
          "location": "San Francisco, CA",
          "dates": "2021 - Present",
          "points": [
            "Led development of microservices architecture serving 10M+ users",
            "Reduced API response time by 40% through optimization",
            "Mentored team of 5 junior developers"
          ]
        },
        {
          "title": "Software Engineer",
          "company": "StartupXYZ",
          "location": "New York, NY",
          "dates": "2018 - 2021",
          "points": [
            "Built real-time data pipeline processing 1M events/day",
            "Implemented CI/CD reducing deployment time by 60%"
          ]
        }
      ],
      "education": [
        {"degree": "M.S. Computer Science", "school": "Stanford University", "year": "2018"},
        {"degree": "B.S. Computer Science", "school": "UC Berkeley", "year": "2016"}
      ],
      "skills": ["Rust", "Python", "TypeScript", "Kubernetes", "AWS", "PostgreSQL", "Redis"]
