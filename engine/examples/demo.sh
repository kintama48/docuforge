echo ""

# Error Handling Demo
echo "9. Error Handling (Syntax Error)"
echo "---------------------------------"
response=$(curl -s -X POST "$BASE_URL/render" \
  -H "Content-Type: application/json" \
  -d '{
    "template": {
      "main": "main.typ",
      "files": {
        "main.typ": "This has an #[unclosed bracket"
      }
    }
  }')
echo "$response" | jq .
echo ""

echo "10. Error Handling (Missing Variable)"
echo "--------------------------------------"
response=$(curl -s -X POST "$BASE_URL/render" \
  -H "Content-Type: application/json" \
  -d '{
    "template": {
      "main": "main.typ",
      "files": {
        "main.typ": "Hello #sys.inputs.undefined_variable"
      }
    }
  }')
echo "$response" | jq .
echo ""

# Custom Timeout Demo
echo "11. Custom Timeout Option"
echo "-------------------------"
curl -s -X POST "$BASE_URL/render" \
  -H "Content-Type: application/json" \
  -d '{
    "template": {
      "main": "main.typ",
      "files": {
        "main.typ": "Quick render with custom timeout"
      }
    },
    "options": {
      "timeout_ms": 3000
    }
  }' \
  --output "$OUTPUT_DIR/08-custom-timeout.pdf"
echo "Generated: $OUTPUT_DIR/08-custom-timeout.pdf"
echo ""

echo "=========================================="
echo "Demo Complete!"
echo "=========================================="
echo ""
echo "Generated PDFs:"
ls -la "$OUTPUT_DIR"/*.pdf
echo ""
echo "View PDFs with: xdg-open $OUTPUT_DIR/01-hello-world.pdf"
